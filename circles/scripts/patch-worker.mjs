// Inlines the circles module into the live Worker's single file (worker/worker.js) and routes /api/sq/c/*.
// Idempotent: re-running replaces the previous circles block. The Worker is uploaded as one script,
// so the module is inlined (inside its own scope) rather than imported.
//
// Usage (from the repo root): node circles/scripts/patch-worker.mjs worker/worker.js
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const target = process.argv[2] || 'worker/worker.js';
let src = readFileSync(target, 'utf8');
const mod = readFileSync(here('../worker/circles/circles.js'), 'utf8').replace(/^export /gm, '');
const sql = readFileSync(here('../migrations/0001_circles.sql'), 'utf8')
  .split('\n').map((l) => l.replace(/--.*$/, '')).join('\n')
  .split(';').map((s) => s.replace(/\s+/g, ' ').trim()).filter(Boolean);

const START = '/* ===== CIRCLES START (generated by circles/scripts/patch-worker.mjs, do not edit by hand) ===== */';
const END = '/* ===== CIRCLES END ===== */';
const block = `${START}
const CIRCLES = (function () {
${mod}
return { handleCircles, circlesCron };
})();
const CIRCLES_SQL = ${JSON.stringify(sql)};
let circlesReady = false;
async function circlesTables(env) {
  if (circlesReady) return;
  for (const q of CIRCLES_SQL) await env.D1.prepare(q).run();
  circlesReady = true;
}
// Circles are on unless CIRCLES_ON is set to something other than "1". CIRCLES_PIDS (optional) limits who can use them.
function circlesEnv(env) { return Object.assign({}, env, { CIRCLES_ON: env.CIRCLES_ON === undefined ? '1' : env.CIRCLES_ON }); }
const circlesSqApi0 = sqApi;
sqApi = async function (req, path, env, body, user, id, r) {
  if (path.indexOf('/api/sq/c/') !== 0) return circlesSqApi0(req, path, env, body, user, id, r);
  try {
    await sqReady(env); await v2Ready(env); await circlesTables(env);
    const mine = await v2Person(env, String(id));
    if (!mine || !mine.pid) return apiJson(req, { ok: false, error: 'Please register first.' }, 403);
    const lookup = async (pids) => {
      if (!pids.length) return {};
      const rows = (await env.D1.prepare('SELECT pid, alias, temples FROM people WHERE pid IN (' + pids.map(() => '?').join(',') + ')').bind(...pids.map(String)).all()).results || [];
      const out = {}; rows.forEach((p) => { out[p.pid] = { alias: p.alias || 'someone', temple: v2Temple(p) }; }); return out;
    };
    const people = async () => ((await env.D1.prepare("SELECT pid, alias, temples FROM people WHERE member = 1 AND pid IS NOT NULL AND pid != '' ORDER BY alias").all()).results || [])
      .map((p) => ({ pid: p.pid, alias: p.alias || 'someone', temple: v2Temple(p) }));
    const out = await CIRCLES.handleCircles(path.slice('/api/sq/c/'.length), body || {}, { db: env.D1, env: circlesEnv(env), pid: String(mine.pid), lookup, people });
    return apiJson(req, out);
  } catch (e) { return apiJson(req, { ok: false, error: 'Something went wrong.' }, 500); }
};
async function circlesScheduled(env) { try { await circlesTables(env); await CIRCLES.circlesCron({ db: env.D1, env: circlesEnv(env) }); } catch (e) {} }
${END}
`;

const s = src.indexOf(START), e = src.indexOf(END);
if (s >= 0 && e > s) src = src.slice(0, s) + block.trimEnd() + src.slice(e + END.length);
else {
  const anchor = 'const dyMainExport = dyMain;';
  if (!src.includes(anchor)) throw new Error('Anchor not found: ' + anchor);
  src = src.replace(anchor, block + anchor);
}
const CRON_OLD = 'try { await v2Drift(env); } catch (e) {} },';
const CRON_NEW = 'try { await v2Drift(env); } catch (e) {} await circlesScheduled(env); },';
if (!src.includes(CRON_NEW)) {
  if (!src.includes(CRON_OLD)) throw new Error('Scheduled handler anchor not found');
  src = src.replace(CRON_OLD, CRON_NEW);
}
writeFileSync(target, src);
console.log('Patched', target);
